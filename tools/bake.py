# Bake preview/data.js from symbols/<name>/ (<name>.json + <name>.atlas + pages + thumb.png).
# usage: python tools/bake.py [root]
import json, base64, os, sys, re
root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
url = lambda p: 'data:image/png;base64,' + base64.b64encode(open(p, 'rb').read()).decode()
pages = lambda at: [l.strip() for l in at.splitlines() if re.search(r'\.(png|jpe?g|webp)$', l.strip(), re.I)]
D = {'symbols': {}}
sd = os.path.join(root, 'symbols')
order = json.load(open(os.path.join(sd, 'order.json'))) if os.path.exists(os.path.join(sd, 'order.json')) else sorted(os.listdir(sd))
for n in order:
    d = os.path.join(sd, n)
    js, at = os.path.join(d, n + '.json'), os.path.join(d, n + '.atlas')
    if not (os.path.exists(js) and os.path.exists(at)):
        continue
    a = open(at).read()
    th = os.path.join(d, 'thumb.png')
    D['symbols'][n] = {'skeleton': open(js).read(), 'atlas': a, 'images': {p: url(os.path.join(d, p)) for p in pages(a)},
                       'thumb': url(th) if os.path.exists(th) else ''}
out = os.path.join(root, 'preview', 'data.js')
open(out, 'w').write('// AUTO-GENERATED by tools/bake.py\nwindow.SYMBOL_DATA = ' + json.dumps(D) + ';\n')
print('data.js', os.path.getsize(out) // 1024, 'KB', list(D['symbols']))
